def convert_state_dict(base_sd, src_sd, same, cast_like, roundtrips):
    new_sd, changed, unmatched, used = dict(base_sd), [], [], {}
    for k, v in src_sd.items():
        cands = (["model.language_model." + k[len("model."):]] if k.startswith("model.") else []) + [k]
        name = next((c for c in cands if c in base_sd and tuple(base_sd[c].shape) == tuple(v.shape)), None)
        if name is None:
            if k == "lm_head.weight" and k not in base_sd:
                continue
            unmatched.append(k)
            continue
        if name in used:
            unmatched.append(k + "  (重複: " + used[name] + " と同じ行き先)")
            continue
        used[name] = k
        nv = cast_like(v, base_sd[name])
        if not any(same(nv, rt(base_sd[name])) for rt in roundtrips):
            changed.append(name)
            new_sd[name] = nv
    uncovered = [k for k in base_sd if k not in used]
    return new_sd, changed, unmatched, uncovered

def load_dir(path):
    sd = {}
    for f in sorted(os.listdir(path)):
        if f.endswith(".safetensors"):
            sd.update(load_file(os.path.join(path, f)))
    return sd

